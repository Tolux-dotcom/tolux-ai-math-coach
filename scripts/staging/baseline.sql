do $$ begin
  if (select count(*) from auth.users) <> 0 then
    raise exception 'Staging bootstrap requires an empty Auth database';
  end if;
end $$;

create or replace function public.rls_auto_enable()
returns event_trigger language plpgsql security definer
set search_path = pg_catalog
as $$
declare cmd record;
begin
  for cmd in select * from pg_event_trigger_ddl_commands()
    where command_tag in ('CREATE TABLE','CREATE TABLE AS','SELECT INTO')
      and object_type in ('table','partitioned table')
  loop
    if cmd.schema_name = 'public' then
      execute format('alter table if exists %s enable row level security',cmd.object_identity);
    end if;
  end loop;
end;
$$;
revoke all on function public.rls_auto_enable() from public, anon, authenticated;

-- Preserve the observed legacy table shape. Do not invent a user_id unique key.
create table if not exists public.student_usage (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid references auth.users(id) on delete cascade,
  questions_used integer default 0,
  is_subscriber boolean default false
);
alter table public.student_usage enable row level security;
revoke all on table public.student_usage from public, anon, authenticated;
grant select on table public.student_usage to authenticated;
grant select, insert, update on table public.student_usage to service_role;
grant usage, select on sequence public.student_usage_id_seq to service_role;
create policy "Enable users to view their own data only" on public.student_usage
  for select to authenticated using ((select auth.uid()) = user_id);
